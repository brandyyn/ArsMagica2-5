package am2.mixin.early.client;

import am2.guis.AMGuiHelper;
import net.minecraft.client.entity.EntityPlayerSP;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(EntityPlayerSP.class)
public abstract class MixinEntityPlayerSP{

	/** Reversed strafing and scrambled movement keys. */
	@Inject(method = "onLivingUpdate", at = @At(value = "INVOKE", target = "Lnet/minecraft/util/MovementInput;updatePlayerMoveState()V", shift = At.Shift.AFTER))
	private void am2$overrideKeyboard(CallbackInfo ci){
		AMGuiHelper.overrideKeyboardInput();
	}
}
